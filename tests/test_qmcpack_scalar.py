def test_analyze_dmc_series_separates_tmove_and_reports_input_errors(tmp_path):
    scalar = tmp_path / "dmc.scalar.dat"
    no_tmove_scalar = tmp_path / "no-tmove.scalar.dat"
    scalar_text = "# index LocalEnergy BlockWeight\n0 -10.0 10\n1 -9.8 11\n3 -10.2 12\n2 -10.0 13\nbad row\n"
    scalar.write_text(scalar_text, encoding="utf-8")
    no_tmove_scalar.write_text(scalar_text, encoding="utf-8")

    parsed = analyze_dmc_series(
        [
            {"scalar_file": str(scalar), "timestep": 0.1, "nonlocalmoves": True, "target_walkers": 100, "potential_label": "Ce-sECP"},
            {"scalar_file": str(no_tmove_scalar), "timestep": 0.1, "nonlocalmoves": False, "target_walkers": 200, "potential_label": "Ce-ONCV"},
        ],
        discard_fraction=0,
        reblock_count=2,
    )

    assert parsed["fits"]["tmove"]["status"] == "not_fit"
    assert parsed["fits"]["no_tmove"]["status"] == "not_fit"
    assert parsed["potential_identity"] == {
        "status": "mixed",
        "potential_labels": ["Ce-ONCV", "Ce-sECP"],
    }
    assert parsed["warnings"] == [
        "Runs use different target_walkers values; inspect population-control comparability.",
        "T-move and no-T-move points were fit separately and must not be combined.",
        "Runs declare multiple potential_label values; do not combine different potentials in one time-step fit.",
        "At least one run has varying BlockWeight; LocalEnergy is reblocked as recorded block values.",
        "At least one scalar file contains malformed rows that were excluded.",
        "At least one scalar file has gaps or nonincreasing block indices.",
    ]
    with pytest.raises(ValueError, match="positive finite timestep"):
        analyze_dmc_series([
            {"scalar_file": str(scalar), "timestep": 0, "nonlocalmoves": True},
        ])


