def test_compare_tmove_locality_shift_requires_matched_timestep(tmp_path):
    tmove = tmp_path / "tmove.scalar.dat"
    no_tmove = tmp_path / "no-tmove.scalar.dat"
    tmove.write_text(
        "# index LocalEnergy\n0 -10.1\n1 -9.9\n2 -9.9\n3 -9.7\n",
        encoding="utf-8",
    )
    no_tmove.write_text(
        "# index LocalEnergy\n0 -10.0\n1 -9.8\n2 -9.8\n3 -9.6\nbad row\n",
        encoding="utf-8",
    )
    arguments = {
        "tmove": {
            "scalar_file": str(tmove),
            "timestep": 0.01,
            "target_walkers": 100,
            "potential_label": "Ce-sECP",
        },
        "no_tmove": {
            "scalar_file": str(no_tmove),
            "timestep": 0.01,
            "target_walkers": 100,
            "potential_label": "Ce-sECP",
        },
        "discard_fraction": 0,
        "reblock_count": 2,
    }

    compared = compare_tmove_locality_shift(**arguments)

    assert compared["no_tmove_minus_tmove_hartree"] == pytest.approx(0.1)
    assert compared["standard_error_hartree"] == pytest.approx(0.141421356237309)
    assert compared["walker_count_comparability"] == {
        "status": "matched",
        "target_walkers": 100,
    }
    assert compared["potential_identity"] == {
        "status": "matched",
        "potential_label": "Ce-sECP",
    }
    assert compared["warnings"] == [
        "At least one scalar file contains malformed rows that were excluded."
    ]
    assert _handle_compare_qmcpack_tmove_locality_shift(arguments) == compared
    unlabeled_tmove = {
        key: value
        for key, value in arguments["tmove"].items()
        if key != "potential_label"
    }
    unlabeled_no_tmove = {
        key: value
        for key, value in arguments["no_tmove"].items()
        if key != "potential_label"
    }
    unlabeled = compare_tmove_locality_shift(
        unlabeled_tmove,
        unlabeled_no_tmove,
        discard_fraction=0,
        reblock_count=2,
    )
    assert unlabeled["potential_identity"] == {
        "status": "not_assessed",
        "reason": "potential_label was not supplied for both matched runs",
    }
