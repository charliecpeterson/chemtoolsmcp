def test_analyze_dmc_series_reblocks_and_fits_tmove_points(tmp_path):
    slow = tmp_path / "slow.scalar.dat"
    fast = tmp_path / "fast.scalar.dat"
    slow.write_text(
        "# index LocalEnergy\n0 -10.1\n1 -9.9\n2 -9.9\n3 -9.7\n",
        encoding="utf-8",
    )
    fast.write_text(
        "# index LocalEnergy\n0 -10.3\n1 -10.1\n2 -10.1\n3 -9.9\n",
        encoding="utf-8",
    )
    arguments = {
        "runs": [
            {"scalar_file": str(slow), "timestep": 0.1, "nonlocalmoves": True, "target_walkers": 100, "potential_label": "Ce-sECP"},
            {"scalar_file": str(fast), "timestep": 0.05, "nonlocalmoves": True, "target_walkers": 100, "potential_label": "Ce-sECP"},
        ],
        "discard_fraction": 0,
        "reblock_count": 2,
    }

    parsed = analyze_dmc_series(**arguments)

    assert [point["local_energy_mean"] for point in parsed["points"]] == [-9.9, -10.1]
    assert [point["local_energy_standard_error"] for point in parsed["points"]] == [
        pytest.approx(0.1),
        pytest.approx(0.1),
    ]
    assert parsed["fits"]["tmove"] == {
        "status": "fit",
        "point_count": 2,
        "timesteps": [0.05, 0.1],
        "zero_timestep_energy": pytest.approx(-10.3),
        "zero_timestep_standard_error": pytest.approx(0.22360679774997896),
        "slope": pytest.approx(4.0),
        "slope_standard_error": pytest.approx(2.8284271247461903),
        "chi_squared": pytest.approx(0.0),
        "degrees_of_freedom": 0,
        "reduced_chi_squared": None,
    }
    assert parsed["potential_identity"] == {
        "status": "uniform",
        "potential_label": "Ce-sECP",
    }
    assert parsed["warnings"] == []
    assert _handle_analyze_qmcpack_dmc_series(arguments) == parsed

    unlabelled = analyze_dmc_series(
        [
            {key: value for key, value in run.items() if key != "potential_label"}
            for run in arguments["runs"]
        ],
        discard_fraction=0,
        reblock_count=2,
    )
    assert unlabelled["potential_identity"] == {
        "status": "not_assessed",
        "reason": "potential_label was not supplied for every run",
        "missing_scalar_files": [str(slow), str(fast)],
    }


def test_analyze_dmc_input_series_binds_controls_from_selected_input_blocks(tmp_path):
    input_path = tmp_path / "campaign.xml"
    input_path.write_text("""\
<simulation>
  <qmc method="vmc"/>
  <qmc method="dmc">
    <parameter name="timestep">0.1</parameter>
    <parameter name="nonlocalmoves">yes</parameter>
    <parameter name="targetWalkers">100</parameter>
  </qmc>
  <qmc method="dmc">
    <parameter name="timestep">0.05</parameter>
    <parameter name="nonlocalmoves">yes</parameter>
    <parameter name="total_walkers">100</parameter>
  </qmc>
</simulation>
""", encoding="utf-8")
    slow = tmp_path / "slow.scalar.dat"
    fast = tmp_path / "fast.scalar.dat"
    slow.write_text("# index LocalEnergy\n0 -10.1\n1 -9.9\n", encoding="utf-8")
    fast.write_text("# index LocalEnergy\n0 -10.2\n1 -10.0\n", encoding="utf-8")
    arguments = {
        "qmcpack_input": str(input_path),
        "runs": [
            {"scalar_file": str(slow), "qmc_block_index": 1, "potential_label": "Ce-sECP"},
            {"scalar_file": str(fast), "qmc_block_index": 2, "potential_label": "Ce-sECP"},
        ],
        "discard_fraction": 0,
        "reblock_count": 2,
    }

    inspected = analyze_dmc_input_series(**arguments)

    assert inspected["schema_version"] == "chemtools.qmcpack-dmc-input-series/1"
    assert inspected["qmcpack_input"] == str(input_path.resolve())
    assert inspected["bindings"] == [
        {
            "scalar_file": str(slow.resolve()),
            "qmc_block_index": 1,
            "dmc_input": {
                "qmc_block_index": 1,
                "timestep": 0.1,
                "blocks": None,
                "target_walkers": 100,
                "nonlocalmoves": True,
            },
            "scalar_filename_project": {
                "status": "not_checked",
                "reason": "The QMCPACK input has no project id.",
            },
        },
        {
            "scalar_file": str(fast.resolve()),
            "qmc_block_index": 2,
            "dmc_input": {
                "qmc_block_index": 2,
                "timestep": 0.05,
                "blocks": None,
                "target_walkers": 100,
                "nonlocalmoves": True,
            },
            "scalar_filename_project": {
                "status": "not_checked",
                "reason": "The QMCPACK input has no project id.",
            },
        },
    ]
    assert [point["timestep"] for point in inspected["analysis"]["points"]] == [0.1, 0.05]
    assert inspected["analysis"]["potential_identity"]["status"] == "uniform"
    assert _handle_analyze_qmcpack_dmc_input_series(arguments) == inspected

    with pytest.raises(ValueError, match="does not select a DMC block"):
        analyze_dmc_input_series(
            input_path,
            [{"scalar_file": str(slow), "qmc_block_index": 0}],
        )


